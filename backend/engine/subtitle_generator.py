import os
from pathlib import Path
from typing import List, Dict, Any

def format_timestamp_srt(seconds: float) -> str:
    millis = int(round((seconds - int(seconds)) * 1000))
    secs = int(seconds) % 60
    mins = (int(seconds) // 60) % 60
    hours = int(seconds) // 3600
    return f"{hours:02d}:{mins:02d}:{secs:02d},{millis:03d}"

def format_timestamp_ass(seconds: float) -> str:
    centis = int(round((seconds - int(seconds)) * 100))
    secs = int(seconds) % 60
    mins = (int(seconds) // 60) % 60
    hours = int(seconds) // 3600
    return f"{hours:01d}:{mins:02d}:{secs:02d}.{centis:02d}"

def generate_srt_file(segments: List[Dict[str, Any]], out_path: str) -> str:
    lines = []
    for idx, seg in enumerate(segments, 1):
        s_time = format_timestamp_srt(seg.get("start", 0.0))
        e_time = format_timestamp_srt(seg.get("end", 0.0))
        text = seg.get("text", "")
        lines.append(f"{idx}\n{s_time} --> {e_time}\n{text}\n")

    content = "\n".join(lines)
    Path(out_path).parent.mkdir(parents=True, exist_ok=True)
    Path(out_path).write_text(content, encoding="utf-8")
    return out_path

def generate_ass_file(
    segments: List[Dict[str, Any]],
    style: Dict[str, Any],
    out_path: str,
    video_width: int = 1920,
    video_height: int = 1080
) -> str:
    font_family = style.get("fontFamily", "Montserrat")
    font_size = style.get("fontSize", 52)
    primary_color = style.get("primaryColor", "&H00FFFFFF")
    highlight_color = style.get("highlightColor", "&H0022D3EE")
    outline_color = style.get("outlineColor", "&H00000000")
    shadow_color = style.get("shadowColor", "&H80000000")
    bold = -1 if style.get("bold", True) else 0
    italic = -1 if style.get("italic", False) else 0
    outline = style.get("outlineWidth", 3)
    shadow = style.get("shadowDepth", 2)
    alignment = style.get("alignment", 2)
    margin_v = style.get("bottomMargin", 60)
    animation_mode = style.get("animationMode", "kinetic")

    header = f"""[Script Info]
; Script generated by AI Video Studio Engine
Title: AI Video Studio Kinetic Typography
ScriptType: v4.00+
WrapStyle: 0
ScaledBorderAndShadow: yes
YCbCr Matrix: TV.709
PlayResX: {video_width}
PlayResY: {video_height}

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Default,{font_family},{font_size},{primary_color},{highlight_color},{outline_color},{shadow_color},{bold},{italic},0,0,100,100,0,0,1,{outline},{shadow},{alignment},40,40,{margin_v},1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""
    events = []
    for seg in segments:
        s_ass = format_timestamp_ass(seg.get("start", 0.0))
        e_ass = format_timestamp_ass(seg.get("end", 0.0))
        words = seg.get("words", [])

        if animation_mode == "kinetic" and words:
            dialogue_parts = []
            for w in words:
                dur_cs = int(round(max(0.05, (w.get("end", 0.0) - w.get("start", 0.0))) * 100))
                w_text = w.get("word", "")
                dialogue_parts.append(f"{{\\kf{dur_cs}}}{w_text}")
            text_line = " ".join(dialogue_parts)
        else:
            text_line = seg.get("text", "")

        events.append(f"Dialogue: 0,{s_ass},{e_ass},Default,,0,0,0,,{text_line}")

    full_ass = header + "\n".join(events) + "\n"
    Path(out_path).parent.mkdir(parents=True, exist_ok=True)
    Path(out_path).write_text(full_ass, encoding="utf-8")
    return out_path
